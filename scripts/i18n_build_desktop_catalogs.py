#!/usr/bin/env python3
"""Generate the bundled Desktop UI catalog without runtime translation requests.

Author Desktop-specific messages only in localization/ui/{uz,ru,tj}/desktop.json.
Shared messages remain owned by common/course catalogs and their existing adapters.
The original Desktop dictionaries are compatibility fallbacks, not authoring sources.

Usage: python scripts/i18n_build_desktop_catalogs.py --write|--check
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ("uz", "ru", "tj")
KEY = re.compile(r"[a-zA-Z][a-zA-Z0-9_]*")
VARIABLE = re.compile(r"\{([a-zA-Z0-9_]+)\}")
TARGET = "desktop/ui/js/generated/hsk-desktop-i18n.js"
AUTO_COMMENT = "Generated by scripts/i18n_build_desktop_catalogs.py; do not edit."


def _unique_pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def _variables(value: str) -> Counter:
    remaining = VARIABLE.sub("", value)
    if "{" in remaining or "}" in remaining:
        raise ValueError("Unsupported placeholder syntax")
    return Counter(VARIABLE.findall(value))


def read_sources(root: Path = ROOT) -> dict[str, dict[str, str]]:
    catalogs = {}
    for locale in LOCALES:
        source = json.loads(
            (root / "localization/ui" / locale / "desktop.json").read_text(encoding="utf-8"),
            object_pairs_hook=_unique_pairs,
        )
        if (not isinstance(source, dict)
                or set(source) != {"schema_version", "namespace", "locale", "messages"}
                or type(source["schema_version"]) is not int
                or source["schema_version"] != 1
                or source["namespace"] != "desktop"
                or source["locale"] != locale):
            raise ValueError(f"Desktop catalog metadata mismatch: {locale}")
        messages = source["messages"]
        if not isinstance(messages, dict) or not messages:
            raise ValueError(f"Empty/non-object Desktop messages: {locale}")
        for key, value in messages.items():
            if (not KEY.fullmatch(key) or "__" in key
                    or key in {"constructor", "prototype"}
                    or not isinstance(value, str) or not value.strip()
                    or "<" in value or ">" in value):
                raise ValueError(f"Untrusted Desktop key/plain text: {locale}/{key}")
            _variables(value)
        catalogs[locale] = messages
    expected = set(catalogs["uz"])
    for locale in LOCALES[1:]:
        if set(catalogs[locale]) != expected:
            raise ValueError(f"Desktop locale key parity mismatch: {locale}")
        for key in expected:
            if _variables(catalogs[locale][key]) != _variables(catalogs["uz"][key]):
                raise ValueError(f"Desktop placeholder parity mismatch: {locale}/{key}")
    return catalogs


def output_files(catalogs: dict[str, dict[str, str]]) -> dict[str, str]:
    def encode(value):
        return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2)
                .replace("\u2028", r"\u2028").replace("\u2029", r"\u2029"))

    body = ",\n".join(
        f'  "{locale}": Object.freeze({encode(catalogs[locale])})'
        for locale in LOCALES
    )
    return {TARGET: (
        f"/* {AUTO_COMMENT} */\n"
        '"use strict";\n'
        'if (typeof window !== "undefined") {\n'
        "  window.HSKAI_DESKTOP_I18N = Object.freeze({\n"
        + body + "\n  });\n}\n"
    )}


def generate(root: Path = ROOT, *, check: bool) -> list[str]:
    changed = []
    for relative, body in output_files(read_sources(root)).items():
        path = root / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != body:
            changed.append(relative)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(body, encoding="utf-8")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        changed = generate(args.root, check=args.check)
    except (OSError, ValueError, UnicodeError, json.JSONDecodeError) as error:
        print("Desktop catalog generation failed:", error, file=sys.stderr)
        return 1
    if args.check and changed:
        print("Stale/missing Desktop artifacts:", ", ".join(changed), file=sys.stderr)
        return 1
    print("Desktop UI catalogs:", len(read_sources(args.root)["uz"]),
          "keys/locale;", len(changed), "updated" if args.write else "stale")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
