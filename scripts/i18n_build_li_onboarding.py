"""Build canonical RU/UZ/TJ Li Panda onboarding copy and option reactions.

Single local-first source: localization/ui/<locale>/li_onboarding.json.
Never invent translations from runtime AI. No Android resource is changed:
this is the shared authenticated PWA / Telegram Mini App web view.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ("uz", "ru", "tj")
NAMESPACE = "li_onboarding"
# Original demo has 66 copy keys; Li's verified HSK 3.0 access gate adds 3.
COPY_COUNT = 69
INSTALL_KEYS = ("install.title", "install.description", "install.videoLabel", "install.videoFallback", "install.step1", "install.step2", "install.step3", "install.note", "install.continue", "install.close",)
SHAPES = {
    "LV20": ("beginner", "hsk1", "hsk2", "hsk3", "hsk4"),
    "LV30": ("nhsk1", "nhsk2", "nhsk3"),
    "GOALS": ("hsk_exam", "daily_communication", "travel", "work_china", "study_china"),
    "TIMES": (5, 10, 15, 20, 30),
    "FOCUS": ("speaking", "listening", "vocabulary", "grammar", "none"),
    "STREAKS": (7, 14, 30, 50),
    "PERKS": ("mic", "exam", "infinity"),
}
FIELDS = {
    "LV20": ("hd", "s", "say"),
    "LV30": ("hd", "s", "say"),
    "GOALS": ("hd", "s", "say"),
    "TIMES": ("say",),
    "FOCUS": ("hd", "say"),
    "STREAKS": ("len", "say"),
    "PERKS": ("t", "s"),
}
STATIC_HEADINGS = {
    "LV20": {"hsk1": "HSK 1", "hsk2": "HSK 2", "hsk3": "HSK 3", "hsk4": "HSK 4"},
    "LV30": {"nhsk1": "HSK 1", "nhsk2": "HSK 2", "nhsk3": "HSK 3"},
}
OUTPUT = "app/static/course_v3_data/hsk-li-onboarding-i18n.js"


def _json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2)


def read_sources(root: Path = ROOT) -> dict[str, dict[str, str]]:
    result = {}
    for lang in LOCALES:
        file = root / "localization/ui" / lang / (NAMESPACE + ".json")
        data = json.loads(file.read_text(encoding="utf-8"))
        if (type(data) is not dict or set(data) !=
                {"schema_version", "namespace", "locale", "messages"} or
                data["schema_version"] != 1 or
                data["locale"] != lang or data["namespace"] != NAMESPACE):
            raise ValueError("invalid Li locale source " + lang)
        messages = data["messages"]
        if (type(messages) is not dict or
                any(type(k) is not str or type(v) is not str or not v.strip()
                    for k, v in messages.items())):
            raise ValueError("invalid Li messages " + lang)
        result[lang] = messages
    keys = set(result["ru"])
    if any(set(result[lang]) != keys for lang in LOCALES):
        raise ValueError("Li locale key parity mismatch")
    copy_keys = {key for key in keys if key.startswith("copy.")}
    if len(copy_keys) != COPY_COUNT:
        raise ValueError("Li canonical copy count changed")
    required = set(copy_keys) | set(INSTALL_KEYS)
    for group, codes in SHAPES.items():
        for code in codes:
            for field in FIELDS[group]:
                if field == "hd" and code in STATIC_HEADINGS.get(group, {}):
                    continue
                required.add(f"{group}.{code}.{field}")
    if keys != required:
        raise ValueError("Li onboarding option catalog changed: " + repr(sorted(keys ^ required)))
    # Canonical text is exact from the supplied user demo; tags are only
    # intended in fixed copy fields, not in option keys/DOM attributes.
    for key in keys:
        if not key.startswith("copy."):
            if any("<" in result[lang][key] or ">" in result[lang][key] for lang in LOCALES):
                raise ValueError("unexpected Li option HTML " + key)
    return result


def output_files(catalogs: dict[str, dict[str, str]]) -> dict[str, str]:
    copy = {
        lang: {
            key.removeprefix("copy."): value
            for key, value in source.items() if key.startswith("copy.") or key in INSTALL_KEYS
        }
        for lang, source in catalogs.items()
    }
    options = {}
    for group, codes in SHAPES.items():
        items = []
        for code in codes:
            row = {("i" if group == "PERKS" else "k"): code}
            for field in FIELDS[group]:
                static = STATIC_HEADINGS.get(group, {}).get(code) if field == "hd" else None
                row[field] = static if static is not None else {
                    lang: catalogs[lang][f"{group}.{code}.{field}"] for lang in LOCALES
                }
            items.append(row)
        options[group] = items
    contents = (
        "/* Generated by scripts/i18n_build_li_onboarding.py; do not edit. */\n"
        '"use strict";\n'
        'if (typeof window !== "undefined") {\n'
        "  window.HSKAI_LI_I18N = " + _json(copy) + ";\n"
        "  window.HSKAI_LI_OPTIONS = " + _json(options) + ";\n"
        "}\n"
    )
    return {OUTPUT: contents}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    args = parser.add_mutually_exclusive_group(required=True)
    args.add_argument("--write", action="store_true")
    args.add_argument("--check", action="store_true")
    options = parser.parse_args()
    generated = output_files(read_sources(ROOT))
    changed = []
    for path, content in generated.items():
        output = ROOT / path
        if not output.is_file() or output.read_text(encoding="utf-8") != content:
            changed.append(path)
            if options.write:
                output.parent.mkdir(parents=True, exist_ok=True)
                output.write_text(content, encoding="utf-8")
    if options.check and changed:
        raise SystemExit("Stale Li onboarding bundles: " + ", ".join(changed))
    print("Li onboarding canonical catalogs:", len(LOCALES), "locales;",
          len(changed), "stale" if options.check else "written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
