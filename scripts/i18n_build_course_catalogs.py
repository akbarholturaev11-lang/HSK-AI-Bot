#!/usr/bin/env python3
"""Generate six local, static course UI artifacts from three validated catalogs.

No lesson JSON, network, AI provider or runtime client is involved. The source
catalog guard must succeed before any artifact is written. These artifacts do
not activate the course translations in a client.

Usage: python scripts/i18n_build_course_catalogs.py --write|--check
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

if __package__:
    from .i18n_course_ui_catalog_guard import LOCALES, ROOT, review_sources
else:
    from i18n_course_ui_catalog_guard import LOCALES, ROOT, review_sources

ANDROID_TAGS = {"uz": "", "ru": "-ru", "tj": "-tg"}
AUTO_COMMENT = "Generated by scripts/i18n_build_course_catalogs.py; do not edit."


def read_sources(root: Path = ROOT) -> dict[str, dict[str, str]]:
    # Validates the strict reviewed key-count schema, locale parity, named placeholders,
    # duplicates and forbidden grading fields before accessing message values.
    review_sources(root)
    return {
        locale: json.loads(
            (root / "localization/ui" / locale / "course.json").read_text(encoding="utf-8")
        )["messages"]
        for locale in LOCALES
    }


def _json(value: object) -> str:
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)
            .replace("\u2028", r"\u2028").replace("\u2029", r"\u2029"))


def android_resource_names(catalog: dict[str, str]) -> dict[str, str]:
    result = {}
    for key in catalog:
        name = "hsk_course_" + re.sub(
            r"([a-z0-9])([A-Z])", r"\1_\2", key.replace(".", "_")
        ).lower()
        if name in result.values():
            raise ValueError("Android course resource-name collision: " + name)
        result[key] = name
    return result


def _android_xml(catalog: dict[str, str]) -> str:
    names = android_resource_names(catalog)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- ' + AUTO_COMMENT + ' -->',
        '<resources>',
    ]
    for key in sorted(catalog):
        # Android/aapt interprets apostrophes and double quotes; XML escaping
        # alone is insufficient for Android string resources.
        value = escape(catalog[key]).replace("'", r"\'").replace('"', r'\"')
        lines.append(f'    <string name="{names[key]}" formatted="false">{value}</string>')
    return "\n".join(lines + ["</resources>", ""])


def _browser_bundle(catalogs: dict[str, dict[str, str]]) -> str:
    body = ",\n".join(
        f'  "{locale}": Object.freeze({_json(catalogs[locale])})'
        for locale in LOCALES
    )
    return (
        "/* " + AUTO_COMMENT + " */\n"
        '"use strict";\n'
        'if (typeof window !== "undefined") {\n'
        '  window.HSKAI_COURSE_I18N = Object.freeze({\n'
        + body + '\n  });\n}\n'
    )


def output_files(catalogs: dict[str, dict[str, str]]) -> dict[str, str]:
    bundle = _browser_bundle(catalogs)
    output = {
        "app/static/course_v3_data/hsk-course-i18n.js": bundle,
        "desktop/ui/js/generated/hsk-course-i18n.js": bundle,
        "app/bot/generated/course_i18n.py": (
            "# " + AUTO_COMMENT + "\n"
            "# Bundled at deploy time; legacy Bot tj locale retained.\n"
            "COURSE_MESSAGES = " + _json(catalogs) + "\n"
        ),
    }
    for locale, tag in ANDROID_TAGS.items():
        output[f"android/app/src/main/res/values{tag}/hsk_course_i18n.xml"] = (
            _android_xml(catalogs[locale])
        )
    return output


def generate(root: Path = ROOT, *, check: bool) -> list[str]:
    outputs = output_files(read_sources(root))
    changed = []
    for relative, body in outputs.items():
        target = root / relative
        if not target.is_file() or target.read_text(encoding="utf-8") != body:
            changed.append(relative)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(body, encoding="utf-8")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        changed = generate(args.root, check=args.check)
    except (OSError, UnicodeError, ValueError) as exc:
        print("Course UI generation failed:", exc, file=sys.stderr)
        return 1
    if args.check and changed:
        print("Stale/missing course UI artifacts:", ", ".join(changed), file=sys.stderr)
        return 1
    print("Local-first course UI:", len(LOCALES), "locales;", len(output_files(read_sources(args.root))),
          "artifacts;", len(changed), "stale" if args.check else "written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
