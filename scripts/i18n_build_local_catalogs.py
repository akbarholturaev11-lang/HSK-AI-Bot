#!/usr/bin/env python3
"""Deterministically generate local-first common UI translations for four targets.

Author ONLY localization/ui/{uz,ru,tj}/common.json. This script needs no
external service, network, packages, AI API or database. It never touches
course/quiz answers, payments or existing live translation dictionaries.

Usage:
  python scripts/i18n_build_local_catalogs.py --write
  python scripts/i18n_build_local_catalogs.py --check
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ("uz", "ru", "tj")
ANDROID_TAGS = {"uz": "", "ru": "-ru", "tj": "-tg"}
SOURCE = "localization/ui"
NAME_RE = re.compile(r"[a-z][a-zA-Z0-9]*(?:\.[a-z][a-zA-Z0-9]*)*")
PLACEHOLDER_RE = re.compile(r"\{([a-zA-Z][a-zA-Z0-9_]*)\}")
AUTO_COMMENT = "Generated by scripts/i18n_build_local_catalogs.py; do not edit."


def _unique_pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError(f"Duplicate JSON key {key!r}")
        result[key] = value
    return result


def _variables(text: str) -> set[str]:
    variables = set(PLACEHOLDER_RE.findall(text))
    residual = PLACEHOLDER_RE.sub("", text)
    if "{" in residual or "}" in residual:
        raise ValueError("Unmatched/unsupported placeholder syntax")
    return variables


def read_sources(root: Path = ROOT) -> dict[str, dict[str, str]]:
    catalogs = {}
    for lang in LANGUAGES:
        source_file = root / SOURCE / lang / "common.json"
        source = json.loads(
            source_file.read_text(encoding="utf-8"), object_pairs_hook=_unique_pairs
        )
        if (source.get("schema_version") != 1
                or source.get("namespace") != "common"
                or source.get("locale") != lang
                or set(source) != {"schema_version", "namespace", "locale", "messages"}):
            raise ValueError(f"Catalog metadata mismatch: {lang}")
        messages = source["messages"]
        if not isinstance(messages, dict) or not messages:
            raise ValueError(f"Empty/non-object messages: {lang}")
        for key, value in messages.items():
            if (not NAME_RE.fullmatch(key) or "__" in key
                    or not isinstance(value, str) or not value.strip()
                    or "<" in value or ">" in value):
                raise ValueError(f"Untrusted key/plain text in {lang}: {key!r}")
            try:
                _variables(value)
            except ValueError as exc:
                raise ValueError(f"{lang}/{key}: {exc}") from exc
        catalogs[lang] = messages
    expected = set(catalogs["uz"])
    for lang in LANGUAGES:
        if set(catalogs[lang]) != expected:
            raise ValueError(
                f"Missing/extra common keys for {lang}: "
                f"missing={sorted(expected - set(catalogs[lang]))}, "
                f"extra={sorted(set(catalogs[lang]) - expected)}"
            )
    for key in sorted(expected):
        variables = _variables(catalogs["uz"][key])
        for lang in LANGUAGES[1:]:
            if _variables(catalogs[lang][key]) != variables:
                raise ValueError(f"Placeholder parity mismatch: {key} / {lang}")
    names = ["hsk_common_" + key.replace(".", "_") for key in expected]
    if len(names) != len(set(names)):
        raise ValueError("Android resource name collision")
    return catalogs


def _json(value: object) -> str:
    # Valid JS/Python-safe for these string-only catalogs; escape separators.
    return (
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)
        .replace("\u2028", r"\u2028")
        .replace("\u2029", r"\u2029")
    )


def _android_xml(catalog: dict[str, str]) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- {AUTO_COMMENT} -->", "<resources>"]
    for key in sorted(catalog):
        name = "hsk_common_" + key.replace(".", "_")
        # Android aapt treats literal apostrophes specially; escape them.
        value = escape(catalog[key]).replace("'", r"\'").replace('"', r'\"')
        lines.append(f'    <string name="{name}" formatted="false">{value}</string>')
    return "\n".join(lines + ["</resources>", ""])


def _browser_bundle(catalogs: dict[str, dict[str, str]]) -> str:
    parts = []
    for lang in LANGUAGES:
        parts.append(f'  "{lang}": Object.freeze({_json(catalogs[lang])})')
    body = ",\n".join(parts)
    return (
        f"/* {AUTO_COMMENT} */\n"
        '"use strict";\n'
        "window.HSKAI_COMMON_I18N = Object.freeze({\n"
        + body + "\n});\n"
    )


def output_files(catalogs: dict[str, dict[str, str]]) -> dict[str, str]:
    out = {
        "app/static/course_v3_data/hsk-common-i18n.js":
            _browser_bundle(catalogs),
        "desktop/ui/js/generated/hsk-common-i18n.js":
            _browser_bundle(catalogs),
        "app/bot/generated/common_i18n.py":
            (f"# {AUTO_COMMENT}\n"
             "# Local, build-time messages; backend locale names remain uz/ru/tj.\n"
             "COMMON_MESSAGES = " + _json(catalogs) + "\n"),
    }
    for lang, tag in ANDROID_TAGS.items():
        out[f"android/app/src/main/res/values{tag}/hsk_common_i18n.xml"] = (
            _android_xml(catalogs[lang])
        )
    return out


def generate(root: Path = ROOT, *, check: bool) -> list[str]:
    expected = output_files(read_sources(root))
    changed = []
    for relative, body in expected.items():
        target = root / relative
        if not target.is_file() or target.read_text(encoding="utf-8") != body:
            changed.append(relative)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(body, encoding="utf-8")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        changed = generate(args.root, check=args.check)
    except (OSError, ValueError, UnicodeError, json.JSONDecodeError) as exc:
        print("Local-first generation failed:", exc, file=sys.stderr)
        return 1
    if args.check and changed:
        print("Generated translations missing/stale:", ", ".join(changed),
              file=sys.stderr)
        return 1
    print("Local-first common catalogs:", len(LANGUAGES), "locales,",
          len(output_files(read_sources(args.root))), "target artifacts,",
          len(changed), "files to update" if args.check else "files written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
