#!/usr/bin/env python3
"""Build fixed notification copy locally; campaign/DB-authored copy stays dynamic.

Author localization/ui/{uz,ru,tj}/notifications.json, then run --write.
The resulting Python constant needs no API, AI provider, database or client fetch.
Only the existing balanced <b> Telegram markup is permitted in fixed templates.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ("uz", "ru", "tj")
TARGET = "app/services/generated/notification_i18n.py"
KEY = re.compile(r"[a-z][a-zA-Z0-9_]*(?:\.[a-z][a-zA-Z0-9_]*)+")
VARIABLE = re.compile(r"\{([a-zA-Z0-9_]+)\}")
TAG = re.compile(r"</?b>")


def _unique_pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def _signature(value: str):
    remaining = VARIABLE.sub("", value)
    if "{" in remaining or "}" in remaining:
        raise ValueError("Unsupported notification placeholder syntax")
    tags = TAG.findall(value)
    plain = TAG.sub("", value)
    if "<" in plain or ">" in plain:
        raise ValueError("Untrusted notification HTML")
    depth = 0
    for tag in tags:
        depth += 1 if tag == "<b>" else -1
        if depth < 0:
            raise ValueError("Unbalanced notification HTML")
    if depth:
        raise ValueError("Unbalanced notification HTML")
    return Counter(VARIABLE.findall(value)), Counter(tags)


def read_sources(root: Path = ROOT) -> dict[str, dict[str, str]]:
    catalogs = {}
    for locale in LOCALES:
        source = json.loads(
            (root / "localization/ui" / locale / "notifications.json").read_text(encoding="utf-8"),
            object_pairs_hook=_unique_pairs,
        )
        if (not isinstance(source, dict)
                or set(source) != {"schema_version", "namespace", "locale", "messages"}
                or type(source["schema_version"]) is not int
                or source["schema_version"] != 1
                or source["namespace"] != "notifications"
                or source["locale"] != locale):
            raise ValueError(f"Notification metadata mismatch: {locale}")
        messages = source["messages"]
        if not isinstance(messages, dict) or not messages:
            raise ValueError(f"Empty/non-object notification messages: {locale}")
        for key, value in messages.items():
            if (not KEY.fullmatch(key) or "__" in key
                    or not isinstance(value, str) or not value.strip()):
                raise ValueError(f"Untrusted notification key/text: {locale}/{key}")
            _signature(value)
        catalogs[locale] = messages
    for locale in LOCALES[1:]:
        if set(catalogs[locale]) != set(catalogs["uz"]):
            raise ValueError(f"Notification locale key parity mismatch: {locale}")
        for key in catalogs["uz"]:
            if _signature(catalogs[locale][key]) != _signature(catalogs["uz"][key]):
                raise ValueError(f"Notification placeholder/HTML parity mismatch: {locale}/{key}")
    return catalogs


def output_files(catalogs: dict[str, dict[str, str]]) -> dict[str, str]:
    return {TARGET: (
        "# Generated by scripts/i18n_build_notification_catalogs.py; do not edit.\n"
        "# Fixed system copy only; custom DB/campaign values retain precedence.\n"
        "NOTIFICATION_MESSAGES = "
        + json.dumps(catalogs, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    )}


def generate(root: Path = ROOT, *, check: bool) -> list[str]:
    changed = []
    for relative, body in output_files(read_sources(root)).items():
        path = root / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != body:
            changed.append(relative)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(body, encoding="utf-8")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        changed = generate(args.root, check=args.check)
    except (OSError, ValueError, UnicodeError, json.JSONDecodeError) as error:
        print("Notification catalog generation failed:", error, file=sys.stderr)
        return 1
    if args.check and changed:
        print("Stale/missing notification artifacts:", ", ".join(changed), file=sys.stderr)
        return 1
    print("Fixed notification catalogs:", len(read_sources(args.root)["uz"]),
          "keys/locale;", len(changed), "updated" if args.write else "stale")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
