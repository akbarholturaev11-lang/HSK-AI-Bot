#!/usr/bin/env python3
"""Run focused native checkout UI checks and retain their screenshots.

Connected instrumentation uninstalls its APK, so copy only named QA images
while the tests run. No device account, private app file or real provider read.
Requires the existing ANDROID_HOME/JAVA_HOME and a running test emulator.
"""
import argparse
import os
from pathlib import Path
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--variant', choices=('direct', 'play'), default='direct')
parser.add_argument('--output', default='/tmp/hsk-checkout-audit')
parser.add_argument('--serial', default='emulator-5554')
args = parser.parse_args()
output = Path(args.output); output.mkdir(parents=True, exist_ok=True)
adb = str(Path(os.environ['ANDROID_HOME']) / 'platform-tools/adb')
classes = ('com.pomp.hskai.feature.subscription.NativeLavaCheckoutTest,'
           'com.pomp.hskai.feature.subscription.SubscriptionCheckoutHostTest,'
           'com.pomp.hskai.feature.limit.SectionLimitOverlayTest') if args.variant == 'direct' else \
          'com.pomp.hskai.feature.limit.SectionLimitOverlayTest'
command = [str(ROOT / 'android/gradlew'), '-p', str(ROOT / 'android'),
           ':app:connected' + args.variant.title() + 'DebugAndroidTest',
           '-Pandroid.testInstrumentationRunnerArguments.class=' + classes, '--console=plain']
captured = {}
# Every accepted file below is generated by the named UI tests on this emulator.
directory = '/sdcard/Android/data/com.pomp.hskai.debug/files/'
with (output / ('native-' + args.variant + '.log')).open('w') as log:
    run = subprocess.Popen(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
    while run.poll() is None:
        listed = subprocess.run([adb, '-s', args.serial, 'shell', 'ls', directory],
                                capture_output=True, text=True)
        if listed.returncode == 0:
            for name in listed.stdout.splitlines():
                if not name.endswith('.png') or not name.startswith(('checkout-', 'neutral-debug-')):
                    continue
                target = output / (args.variant + '-' + name)
                if name in captured:
                    continue
                result = subprocess.run([adb, '-s', args.serial, 'pull', directory + name, str(target)],
                                        capture_output=True)
                if result.returncode == 0:
                    data = target.read_bytes()
                    if data.startswith(b'\x89PNG\r\n\x1a\n') and data.endswith(b'IEND\xaeB`\x82'):
                        captured[name] = len(data)
                    else:
                        target.unlink(missing_ok=True)
        time.sleep(.4)
print(f'{args.variant}: UI exit={run.returncode}; retained screenshots={len(captured)}')
raise SystemExit(run.returncode)
